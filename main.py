def clean_ai_answer(text):
    """Remove accidental HTML/code generated by the AI."""

    if not text:
        return ""

    text = str(text)

    # Remove fenced code blocks.
    text = re.sub(r"```[\s\S]*?```", "", text)

    # Remove HTML tags.
    text = re.sub(r"<[^>]+>", "", text)

    # Remove common HTML attribute-only lines.
    text = re.sub(
        r"^\s*(class|href|target|style|rel)\s*=.*$",
        "",
        text,
        flags=re.IGNORECASE | re.MULTILINE
    )

    # Remove leftover HTML tag lines.
    text = re.sub(
        r"^\s*</?(a|p|div|span|style|section|br)\s*>\s*$",
        "",
        text,
        flags=re.IGNORECASE | re.MULTILINE
    )

    # Remove an accidental Related Articles heading.
    text = re.sub(
        r"^\s*#{1,6}\s*Related Articles\s*$",
        "",
        text,
        flags=re.IGNORECASE | re.MULTILINE
    )

    text = html.unescape(text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


