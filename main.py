def get_db():
    conn = sqlite3.connect(DB_FILE, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    conn = get_db()
    cur = conn.cursor()

    cur.execute("""
        CREATE TABLE IF NOT EXISTS chats (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        )
    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS messages (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            chat_id INTEGER NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL,
            created_at TEXT NOT NULL,
            links_json TEXT,
            FOREIGN KEY(chat_id) REFERENCES chats(id)
        )
    """)

    columns = [
        row[1]
        for row in cur.execute("PRAGMA table_info(messages)").fetchall()
    ]

    if "links_json" not in columns:
        cur.execute("ALTER TABLE messages ADD COLUMN links_json TEXT")

    conn.commit()
    conn.close()


def create_chat(title="New Chat"):
    now = datetime.now().isoformat(timespec="seconds")
    conn = get_db()

    cur = conn.cursor()
    cur.execute(
        """
        INSERT INTO chats (title, created_at, updated_at)
        VALUES (?, ?, ?)
        """,
        (title, now, now)
    )

    chat_id = cur.lastrowid
    conn.commit()
    conn.close()

    return chat_id


def update_chat_title(chat_id, title):
    now = datetime.now().isoformat(timespec="seconds")
    conn = get_db()

    conn.execute(
        """
        UPDATE chats
        SET title = ?, updated_at = ?
        WHERE id = ?
        """,
        (title[:80], now, chat_id)
    )

    conn.commit()
    conn.close()


def add_message(chat_id, role, content, links=None):
    now = datetime.now().isoformat(timespec="seconds")
    conn = get_db()

    links_json = json.dumps(links, ensure_ascii=False) if links else None

    conn.execute(
        """
        INSERT INTO messages
        (chat_id, role, content, created_at, links_json)
        VALUES (?, ?, ?, ?, ?)
        """,
        (chat_id, role, content, now, links_json)
    )

    conn.execute(
        """
        UPDATE chats
        SET updated_at = ?
        WHERE id = ?
        """,
        (now, chat_id)
    )

    conn.commit()
    conn.close()


def get_chats():
    conn = get_db()

    rows = conn.execute(
        """
        SELECT id, title, created_at, updated_at
        FROM chats
        ORDER BY updated_at DESC
        """
    ).fetchall()

    conn.close()
    return rows


def get_messages(chat_id):
    conn = get_db()

    rows = conn.execute(
        """
        SELECT role, content, created_at, links_json
        FROM messages
        WHERE chat_id = ?
        ORDER BY id ASC
        """,
        (chat_id,)
    ).fetchall()

    conn.close()
    return rows


def clear_all_chats():
    conn = get_db()
    conn.execute("DELETE FROM messages")
    conn.execute("DELETE FROM chats")
    conn.commit()
    conn.close()


